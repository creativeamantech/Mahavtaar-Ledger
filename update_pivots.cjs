const fs = require('fs');

const files = [
  'src/pages/CityPivot.tsx',
  'src/pages/ExecTeamPerf.tsx',
  'src/pages/TeamPivot.tsx',
  'src/pages/BandExplorer.tsx'
];

for (const file of files) {
  let content = fs.readFileSync(file, 'utf8');

  // We need Checkbox in imports
  if (!content.includes('Checkbox')) {
    content = content.replace(/import \{ Popover/, "import { Checkbox } from '../components/ui/checkbox';\nimport { Popover");
  }

  // State replacement
  content = content.replace(/const \[sortKey, setSortKey\] = useState<string>\(''\);\n\s*const \[sortDirection, setSortDirection\] = useState<'asc' \| 'desc'>\('asc'\);/, `const [sortConfig, setSortConfig] = useState<{key: string, direction: 'asc' | 'desc'}[]>([]);`);

  // Sorting logic for sortConfig array
  let sortingRegex;
  if (file === 'src/pages/BandExplorer.tsx') {
    sortingRegex = /if \(sortKey\) \{\s*filtered\.sort\(\(a: any, b: any\) => \{\s*let valA = a\[sortKey\];.*?return sortDirection === 'asc' \? valA\.localeCompare\(valB\) : valB\.localeCompare\(valA\);\s*\}\);\s*\}/s;
  } else {
    sortingRegex = /if \(sortKey\) \{\s*data\.sort\(\(a: any, b: any\) => \{\s*let valA = a\[sortKey\];.*?return sortDirection === 'asc' \? valA\.localeCompare\(valB\) : valB\.localeCompare\(valA\);\s*\}\);\s*\}/s;
  }

  const multiSortLogic = `
    if (sortConfig.length > 0) {
      ${file === 'src/pages/BandExplorer.tsx' ? 'filtered' : 'data'}.sort((a: any, b: any) => {
        for (const sort of sortConfig) {
          let valA = a[sort.key];
          let valB = b[sort.key];
          
          if (sort.key === 'pct') {
            valA = a.totalPOS ? a.paidPOS / a.totalPOS : 0;
            valB = b.totalPOS ? b.paidPOS / b.totalPOS : 0;
          }

          const numA = Number(valA);
          const numB = Number(valB);
          
          let comp = 0;
          if (!isNaN(numA) && !isNaN(numB) && valA !== '' && valB !== '') {
            comp = sort.direction === 'asc' ? numA - numB : numB - numA;
          } else {
            valA = String(valA || '').toLowerCase();
            valB = String(valB || '').toLowerCase();
            comp = sort.direction === 'asc' ? valA.localeCompare(valB) : valB.localeCompare(valA);
          }
          if (comp !== 0) return comp;
        }
        return 0;
      });
    }`;

  content = content.replace(sortingRegex, multiSortLogic);
  
  // Dependency arrays
  content = content.replace(/, sortKey, sortDirection\]\)/g, ', sortConfig])');

  // Popover buttons logic
  const buttonRegex = /<button \s*onClick=\{\(\) => \{ setSortKey\('[^']+'\); setSortDirection\('asc'\); \}\}\s*className="text-left px-2 py-1\.5 text-xs rounded hover:bg-muted transition-colors"\s*>\s*[^<]+\s*<\/button>/g;
  
  // We need to map options inside the file instead of regex replacing buttons directly, because the options are generated by map inside the code.
  // Let's replace the inner part of {sortOptions.map(opt => ... )}
  content = content.replace(
    /<button \s*onClick=\{\(\) => \{ setSortKey\('?\$\{opt\.key\}'?\); setSortDirection\('asc'\); \}\}\s*className="text-left px-2 py-1\.5 text-xs rounded hover:bg-muted transition-colors"\s*>\s*\{opt\.label\}\s*<\/button>/s,
    `<div key={opt.key} className="flex items-center gap-2 px-2 py-1.5 hover:bg-muted rounded transition-colors cursor-pointer" onClick={() => {
        setSortConfig(prev => {
          const exists = prev.find(s => s.key === opt.key);
          if (exists) return prev.filter(s => s.key !== opt.key);
          return [...prev, { key: opt.key, direction: 'asc' }];
        });
      }}>
        <Checkbox checked={!!sortConfig.find(s => s.key === opt.key)} />
        <span className="text-xs truncate flex-1">{opt.label}</span>
      </div>`
  );

  // Active pills
  const oldPill = /\{sortKey && \([\s\S]*?<\/div>\s*\)\}/s;
  
  const newPill = `
    {sortConfig.map(sort => {
      const opt = sortOptions.find(o => o.key === sort.key);
      return (
        <div key={sort.key} className="flex h-8 items-center gap-1.5 bg-muted/50 border border-border px-2 rounded-md text-xs font-bold uppercase tracking-wider text-foreground">
          Sort: {opt ? opt.label : sort.key}
          <button onClick={() => setSortConfig(prev => prev.map(s => s.key === sort.key ? { ...s, direction: s.direction === 'asc' ? 'desc' : 'asc' } : s))} className="ml-1 text-muted-foreground hover:text-foreground">
            {sort.direction === 'asc' ? <ArrowUp className="h-3.5 w-3.5" /> : <ArrowDown className="h-3.5 w-3.5" />}
          </button>
          <button onClick={() => setSortConfig(prev => prev.filter(s => s.key !== sort.key))} className="ml-1 text-muted-foreground hover:text-destructive">
            <X className="h-3.5 w-3.5" />
          </button>
        </div>
      );
    })}
  `;
  
  content = content.replace(oldPill, newPill);
  
  fs.writeFileSync(file, content, 'utf8');
}
